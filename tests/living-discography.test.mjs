import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url),M=require('../fm/living/engine.js');
const tracks=JSON.parse(readFileSync('fm/rotation.json','utf8')).tracks;
assert.equal(tracks.length,21);
execFileSync(process.execPath,['--check','fm/living/engine.js']);
execFileSync(process.execPath,['--check','fm/living/desk.js']);
const page=readFileSync('fm/living/index.html','utf8');
for(const required of ['id="first"','id="second"','id="cards"','id="rundown"','id="import"'])assert(page.includes(required));
assert(!page.includes('autoplay')&&!page.includes('supabase.co'));
let state=M.empty();
const id='source-001',at='2026-11-14T15:00:00Z';
const draft=M.makeDraft({firstId:tracks[0].id,secondId:tracks[1].id,mode:'interpretation',relation:'echo',reason:'A proposed relationship'},tracks,id,at);
assert.equal(draft.status,'draft');state.cards.push(draft);
assert.throws(()=>M.makeDraft({firstId:tracks[0].id,secondId:tracks[0].id,mode:'observation',relation:'echo',reason:'x'},tracks,'x',at));
assert.throws(()=>M.change(draft,'air',{by:'host',at,confirmed:true}),/Not a permitted/);
assert.equal(M.rundown(state.cards).cards.length,0);
const ready=M.change(draft,'ready',{by:'human producer',at});
assert.equal(ready.status,'ready');assert.equal(draft.status,'draft');state.cards[0]=ready;
assert.equal(M.rundown(state.cards).cards.length,1);
assert.equal(M.rundown(state.cards).cards[0].broadcastingAuthorized,false);
assert.throws(()=>M.change(ready,'air',{by:'host',at}),/human confirmation/);
const aired=M.change(ready,'air',{by:'host witness',at,confirmed:true});state.cards[0]=aired;
assert.equal(M.memory(state.cards).witnessedAirs,1);
const returned=M.change(aired,'return',{by:'host witness',at,note:'We really heard it',verdict:'weird'});state.cards[0]=returned;
assert.equal(M.memory(state.cards).explicitVerdicts.weird,1);
const reopened=M.reopen(returned,tracks,'source-002',at);state.cards.push(reopened);
assert.equal(M.memory(state.cards).witnessedAirs,1,'Reopened drafts must not rewrite on-air memory');
assert.equal(reopened.parentId,'source-001');
assert.equal(M.validate(JSON.parse(JSON.stringify(state)),tracks).cards.length,2);
assert.throws(()=>M.validate({...state,cards:[{...returned,events:[]}]},tracks),/witness/);
assert.throws(()=>M.validate({...state,cards:[{...draft,firstId:'invisible'}]},tracks),/Invalid/);
console.log('Living Discography / Kinship-inspired producer state passes.');
