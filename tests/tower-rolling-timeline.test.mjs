import assert from "node:assert/strict";
import {projectTimeline,readTimeline} from "../fm/load/rolling-timeline-core.mjs";
const t=Date.parse("2026-11-27T17:00:00Z"),iso=x=>new Date(t+x*1000).toISOString();
const cue=(id,a,b,current=false,revision="r1")=>({revision,is_current:current,start_at_utc:iso(a),end_at_utc:iso(b),track:{id,title:id,artist:"HUMKIN"}});
const raw={schema:"humkin.autopilot.public-schedule/v1",station_id:"station-one",revision:"r1",as_of_utc:iso(15),clock_at_utc:iso(0),on_air:true,upcoming:[cue("one",-60,60,true),cue("two",60,180),cue("three",180,3700,false,"r2"),cue("four",3700,4000,false,"r2")],pending_revisions:[{revision:"r2",effective_at_utc:iso(180)}]};
const now={mode:"cloud_autopilot_hls",on_air:true,frequency:"station-one",revision:"r1",media_at:iso(-5),track:{id:"one"}};
assert(projectTimeline(raw,now,"station-one").confirmed);
assert.throws(()=>projectTimeline(raw,now,"lo-fi"));
for(const [key,value] of [["frequency","mutant"],["revision","r2"],["track",{id:"two"}],["media_at",iso(-50)]])assert(!projectTimeline(raw,{...now,[key]:value},"station-one").confirmed);
assert(!projectTimeline({...raw,on_air:false},now,"station-one").confirmed);
assert.equal(projectTimeline(raw,now,"station-one",60).rows.length,3);
assert.equal(projectTimeline(raw,now,"station-one",120).rows.length,4);
assert.throws(()=>projectTimeline({...raw,upcoming:[cue("one",-60,60,true),cue("two",59,180)]},now,"station-one"));
assert.throws(()=>projectTimeline({...raw,upcoming:[cue("one",-60,60),cue("two",60,180,true)]},now,"station-one"));
assert.equal(projectTimeline(raw,now,"station-one").pending[0].revision,"r2");
assert.equal(projectTimeline({...raw,on_air:false},null,"station-one").rows.length,3);
const signal={aborted:false},fixture=(status,body)=>({status,json:async()=>body});
assert((await readTimeline("lo-fi",signal,async()=>fixture(503,{mode:"cloud_autopilot_unpublished"}))).unpublished);
const good=await readTimeline("station-one",signal,async url=>url.endsWith("/schedule")?fixture(200,raw):fixture(200,now));
assert.equal(good.raw,raw);assert.equal(good.nowPlaying,now);
console.log("Rolling timeline projection and receipt checks passed");
